// The file-size guard's skip list, and the lister the repository test uses. From docs/BACKLOG.md, item Q4:
//   "Changed at the start of batch 7": "Notebooks (`NotebookEdit`, `.ipynb`) are skipped" and "Generated and vendored
//   files are found with `git check-attr linguist-generated linguist-vendored`, ignored ones with `git check-ignore`,
//   which handle nested `.gitattributes` and patterns; without git or outside a repository those two rules do not
//   apply. Header markers are read from the first 5 lines."
//   (The quote below names the markers, so it stays below line 5 or this file would count as generated.)
//   "What it does": "Skipped: lockfiles by name across ecosystems (...); files marked generated or vendored
//   (`linguist-generated` or `linguist-vendored` in `.gitattributes`, an `@generated` or "DO NOT EDIT" header);
//   git-ignored paths; minified files; binaries; and a configured exclude list."
//   "Changed at the start of Q4": "The skip rules that cost a process (`git check-attr`, `git check-ignore`) run only
//   when the change would be refused."
import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { symlinkSync } from 'node:fs';
import { join } from 'node:path';
import { tempDir } from './helpers.mjs';
import { LIMIT_BYTES, put, write, check, checkGit, hook, makeRepo, plainDir, git, cleanEnv } from './file-size-guard.helpers.mjs';
import { listOversized, runGit } from '../hooks/guards/file-size-guard.mjs';

const big = 'a'.repeat(LIMIT_BYTES + 1);
const LOCKFILES = [
  'package-lock.json', 'npm-shrinkwrap.json', 'yarn.lock', 'pnpm-lock.yaml', 'bun.lock', 'Cargo.lock', 'poetry.lock',
  'uv.lock', 'Pipfile.lock', 'Gemfile.lock', 'composer.lock', 'go.sum', 'mix.lock', 'pubspec.lock', 'Podfile.lock',
  'packages.lock.json', 'flake.lock', 'deno.lock', 'gradle.lockfile', 'Package.resolved',
];

describe('file-size guard: skipped by name or content', () => {
  test('lockfiles, by name in any folder', () => {
    const p = tempDir();
    for (const name of LOCKFILES) assert.equal(check(write(p, `sub/${name}`, big), p).reason, null, name);
    assert.ok(check(write(p, 'sub/lock.json', big), p).reason);
  });

  test('notebooks', () => {
    const p = tempDir();
    assert.equal(check(write(p, 'nb/analysis.ipynb', big), p).reason, null);
  });

  test('minified files', () => {
    const p = tempDir();
    assert.equal(check(write(p, 'web/app.min.js', big), p).reason, null);
    assert.equal(check(write(p, 'web/app.min.css', big), p).reason, null);
    assert.ok(check(write(p, 'web/admin.js', big), p).reason);
  });

  test('binaries: a NUL byte in the content', () => {
    const p = tempDir();
    assert.equal(check(write(p, 'img/x.dat', 'GIF89a\u0000' + big), p).reason, null);
  });

  test('@generated or DO NOT EDIT in the first 5 lines', () => {
    const p = tempDir();
    const lines = (n, marker) => '\n'.repeat(n) + `// ${marker}\n` + big;
    assert.equal(check(write(p, 'gen/a.go', lines(0, '@generated')), p).reason, null);
    assert.equal(check(write(p, 'gen/b.go', lines(4, 'Code generated by tool. DO NOT EDIT.')), p).reason, null);
    assert.ok(check(write(p, 'gen/c.go', lines(5, '@generated')), p).reason);
  });

  test('ignorePaths globs', () => {
    const p = tempDir();
    const options = { ignorePaths: ['fixtures/**', '*.snap'] };
    assert.equal(check(write(p, 'fixtures/deep/x.json', big), p, options).reason, null);
    assert.equal(check(write(p, 'src/__snapshots__/a.snap', big), p, options).reason, null);
    assert.ok(check(write(p, 'src/a.json', big), p, options).reason);
  });
});

describe('file-size guard: git rules', () => {
  test('linguist-generated and linguist-vendored, also from a nested .gitattributes', () => {
    const p = makeRepo();
    put(p, '.gitattributes', 'gen/** linguist-generated\nvendor/** linguist-vendored=true\n');
    put(p, 'sub/.gitattributes', 'out.js linguist-generated=true\n');
    assert.equal(checkGit(write(p, 'gen/a.js', big), p), null);
    assert.equal(checkGit(write(p, 'vendor/lib/b.js', big), p), null);
    assert.equal(checkGit(write(p, 'sub/out.js', big), p), null);
    assert.ok(checkGit(write(p, 'src/c.js', big), p));
  });

  test('-linguist-generated and =false do not skip', () => {
    const p = makeRepo();
    put(p, '.gitattributes', 'a.js -linguist-generated\nb.js linguist-generated=false\nc.js linguist-vendored=false\n');
    for (const f of ['a.js', 'b.js', 'c.js']) assert.ok(checkGit(write(p, f, big), p), f);
  });

  test('git-ignored paths', () => {
    const p = makeRepo();
    put(p, '.gitignore', 'build/\n*.out\n');
    assert.equal(checkGit(write(p, 'build/x.js', big), p), null);
    assert.equal(checkGit(write(p, 'run.out', big), p), null);
    assert.ok(checkGit(write(p, 'run.js', big), p));
  });

  test('outside a repository the git rules do not apply', () => {
    const { dir: p, env } = plainDir();
    put(p, '.gitattributes', 'gen/** linguist-generated\n');
    put(p, '.gitignore', 'build/\n');
    assert.ok(checkGit(write(p, 'gen/a.js', big), p, env));
    assert.ok(checkGit(write(p, 'build/a.js', big), p, env));
    assert.equal(hook(p, write(p, 'build/a.js', big), env).code, 2);
  });

  test('a file in its own repository inside a folder the outer one ignores is still refused', () => {
    const outer = makeRepo();
    put(outer, '.gitignore', 'work/\n');
    const inner = makeRepo(join(outer, 'work', 'inner'));
    assert.ok(checkGit(write(inner, 'src/a.js', big), outer));
    assert.equal(hook(outer, write(inner, 'src/a.js', big)).code, 2);
    assert.equal(hook(outer, write(outer, 'work/loose.js', big)).code, 0);
  });
});

describe('file-size guard: the lister', () => {
  test('lists a tracked file over its limit, with one check-attr call for the candidates only', () => {
    const p = makeRepo();
    put(p, 'src/big.js', big);
    put(p, 'src/small.js', 'x');
    put(p, 'gen/out.js', big);
    put(p, '.gitattributes', 'gen/** linguist-generated\n');
    put(p, 'yarn.lock', big);
    put(p, 'data/blob.bin', 'x\u0000' + big);
    put(p, 'docs/huge.md', 'b'.repeat(40001));
    symlinkSync('big.js', join(p, 'src', 'link.js'));
    git(p, 'add', '-A');
    git(p, 'commit', '-q', '-m', 'fixture');
    put(p, 'src/untracked.js', big);
    const calls = [];
    const spy = (args, cwd) => { calls.push(args); return runGit(args, cwd, cleanEnv()); };
    const over = listOversized(p, { pathLimits: { 'docs/**': 20000 } }, { git: spy });
    assert.deepEqual(over, [{ path: 'src/big.js', tokens: 5001, limit: 5000 }]);
    const attr = calls.filter((a) => a.includes('check-attr'));
    assert.equal(attr.length, 1);
    const paths = attr[0].slice(attr[0].indexOf('--') + 1);
    assert.deepEqual(paths.sort(), ['gen/out.js', 'src/big.js']);
  });

  test('makes no check-attr call when nothing is over', () => {
    const p = makeRepo();
    put(p, 'a.js', 'x');
    git(p, 'add', '-A');
    git(p, 'commit', '-q', '-m', 'one');
    const calls = [];
    assert.deepEqual(listOversized(p, {}, { git: (args, cwd) => { calls.push(args); return runGit(args, cwd, cleanEnv()); } }), []);
    assert.equal(calls.filter((a) => a.includes('check-attr')).length, 0);
  });
});
